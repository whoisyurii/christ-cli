//! Localized Bible book names, indexed against `BOOKS` order.
//!
//! Inputs are matched through `books::canon`, so diacritics, case, dots,
//! spaces, and hyphens don't matter ("joao", "João", "1. Mose" all work).

use crate::data::books::{canon, canon_strict};

pub struct LocalizedBook {
    /// Index into `books::BOOKS`.
    pub idx: usize,
    /// Printed names, primary first (native script).
    pub names: &'static [&'static str],
    /// Abbreviations users commonly type.
    pub abbrevs: &'static [&'static str],
}

pub struct LanguageTable {
    pub lang: &'static str,
    pub books: &'static [LocalizedBook],
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::data::books::BOOKS;
    use std::collections::HashMap;

    #[test]
    fn every_language_covers_all_66_books_in_order() {
        for table in LANGUAGES {
            assert_eq!(table.books.len(), 66, "{}", table.lang);
            for (i, b) in table.books.iter().enumerate() {
                assert_eq!(b.idx, i, "{} entry {} misaligned", table.lang, i);
                assert!(!b.names.is_empty(), "{} entry {} has no names", table.lang, i);
            }
        }
    }

    /// Assert `key` never claims two different book indices within `claims`.
    fn claim(claims: &mut HashMap<String, (usize, String)>, key: String, idx: usize, src: String) {
        if let Some((prev_idx, prev_src)) = claims.get(&key) {
            assert_eq!(
                *prev_idx, idx,
                "'{}' maps to book {} ({}) but also {} ({})",
                key, prev_idx, prev_src, idx, src
            );
        } else {
            claims.insert(key, (idx, src));
        }
    }

    /// Each lookup pass is first-match-wins across languages, so within a
    /// pass a canonical string claiming two different books would silently
    /// mis-resolve. English names/abbrevs participate in every pass because
    /// English matching runs first. Cross-pass overlap (an abbreviation
    /// equal to another book's folded name, like "jo" = João's abbrev vs
    /// Jó folded) is legal — precedence decides it.
    #[test]
    fn no_lookup_pass_resolves_a_string_to_two_different_books() {
        let mut english: HashMap<String, (usize, String)> = HashMap::new();
        for (i, b) in BOOKS.iter().enumerate() {
            claim(&mut english, canon(b.name), i, "English".to_string());
            for a in b.abbrevs {
                claim(&mut english, canon(a), i, "English".to_string());
            }
        }

        // Pass 1: strict (diacritics-preserving) names.
        let mut strict_names = english.clone();
        for table in LANGUAGES {
            for b in table.books {
                for n in b.names {
                    claim(&mut strict_names, canon_strict(n), b.idx, table.lang.to_string());
                }
            }
        }

        // Pass 2: abbreviations (folded).
        let mut abbrevs = english.clone();
        for table in LANGUAGES {
            for b in table.books {
                for a in b.abbrevs {
                    claim(&mut abbrevs, canon(a), b.idx, table.lang.to_string());
                }
            }
        }

        // Pass 3: folded names.
        let mut folded_names = english;
        for table in LANGUAGES {
            for b in table.books {
                for n in b.names {
                    claim(&mut folded_names, canon(n), b.idx, table.lang.to_string());
                }
            }
        }
    }
}

/// Look up a book by localized name across all languages.
///
/// `strict` keeps diacritics (`books::canon_strict`), `folded` folds them
/// (`books::canon`). Precedence: exact printed name (diacritics intact) >
/// abbreviation > diacritic-folded name > unambiguous name prefix. The
/// strict pass keeps Portuguese "Jó" (Job) from swallowing "Jo", the
/// standard abbreviation for João (John); the prefix pass refuses inputs
/// that would match different books in different languages (e.g. "1 Цар"
/// is 1 Samuel to a Russian reader but prefixes Ukrainian 1 Kings).
pub fn lookup(strict: &str, folded: &str) -> Option<usize> {
    for table in LANGUAGES {
        for book in table.books {
            if book.names.iter().any(|n| canon_strict(n) == strict) {
                return Some(book.idx);
            }
        }
    }

    for table in LANGUAGES {
        for book in table.books {
            if book.abbrevs.iter().any(|a| canon(a) == folded) {
                return Some(book.idx);
            }
        }
    }

    for table in LANGUAGES {
        for book in table.books {
            if book.names.iter().any(|n| canon(n) == folded) {
                return Some(book.idx);
            }
        }
    }

    if folded.chars().count() >= 3 {
        let mut unique: Option<usize> = None;
        for table in LANGUAGES {
            for book in table.books {
                if book.names.iter().any(|n| canon(n).starts_with(folded)) {
                    match unique {
                        Some(idx) if idx != book.idx => return None, // ambiguous
                        _ => unique = Some(book.idx),
                    }
                }
            }
        }
        return unique;
    }

    None
}

